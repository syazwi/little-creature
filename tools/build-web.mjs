// Little Creature — bundles the whole game into ONE self-contained HTML file: dist/LittleCreature.html
// (Phaser, game code, font and icon are inlined), so it can be copied to any computer and double-clicked.
// Also builds dist/LittleCreature_full.html: a TESTING build with everything unlocked (src/cheats.js) and its own save.
// Usage: node tools/build-web.mjs
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const read = (p) => readFileSync(join(ROOT, p));
const b64 = (p) => read(p).toString('base64');

function bundle(html, out) {
  // 1) drop the CDN fallback (Phaser is inlined below)
  html = html.replace(/\s*<script>window\.Phaser \|\|[^\n]*<\/script>/, '');
  // 2) inline every local <script src>
  html = html.replace(/<script src="([^"]+)"><\/script>/g, (m, src) => {
    const code = read(src).toString('utf8').replace(/<\/script/gi, '<\\/script');
    return `<script>/* ${src} */\n${code}\n</script>`;
  });
  // 3) fonts and icons as data URIs
  html = html.replace(/url\((lib\/fonts\/[^)]+\.woff2)\)/g, (m, p) => `url(data:font/woff2;base64,${b64(p)})`);
  const icon = `data:image/png;base64,${b64('icons/icon-192.png')}`;
  html = html.replace(/href="icons\/icon-192\.png"/g, `href="${icon}"`);
  if (/<script src=|url\(lib\//.test(html)) throw new Error('some local resources were not inlined');
  mkdirSync(join(ROOT, 'dist'), { recursive: true });
  writeFileSync(join(ROOT, out), html);
  console.log(`${out}  ${(html.length / 1024 / 1024).toFixed(2)} MB`);
}

// 0) stamp the version (from android/app/build.gradle) and the build time into src/version.js, and publish the same
//    in dist/version.json: the game compares the two to tell players a newer version is on GitHub.
function stampVersion() {
  const gradle = read('android/app/build.gradle').toString('utf8');
  const code = +(gradle.match(/versionCode\s+(\d+)/) || [])[1], name = (gradle.match(/versionName\s+'([^']+)'/) || [])[1];
  if (!code || !name) throw new Error('could not read versionCode / versionName from android/app/build.gradle');
  let repo = 'syazwi/little-creature';
  try {
    const m = read('.git/config').toString('utf8').match(/\[remote "origin"\][^[]*?url\s*=\s*\S*github\.com[:/]([^/\s]+\/[^/\s]+?)(?:\.git)?\s/);
    if (m) repo = m[1];
  } catch (e) { /* not a git checkout: keep the default */ }
  const built = new Date().toISOString(), raw = `https://raw.githubusercontent.com/${repo}/main/dist/`, blob = `https://github.com/${repo}/blob/main/dist/`;
  const v = { code, name, built };
  writeFileSync(join(ROOT, 'src/version.js'),
    `/* Generated by tools/build-web.mjs when the game is built: this version, and where to look for a newer one. Do not edit. */\n` +
    `window.LC = window.LC || {};\nLC.VERSION = ${JSON.stringify(v)};\n` +
    `LC.UPDATE_URLS = ${JSON.stringify({ check: raw + 'version.json', apk: `https://github.com/${repo}/raw/main/dist/LittleCreature.apk`, page: blob + 'LittleCreature.html', full: blob + 'LittleCreature_full.html' })};\n`);
  mkdirSync(join(ROOT, 'dist'), { recursive: true });
  writeFileSync(join(ROOT, 'dist/version.json'), JSON.stringify(v, null, 2) + '\n');
  console.log(`version ${name} (${code}), built ${built}`);
  return v;
}
const ver = stampVersion();
const page = read('index.html').toString('utf8');

// 0b) v2.4.2: stamp sw.js (the hosted web version, how iPhones play it) with this build and the full list of files
//     index.html loads, so a new build always reaches phones and no file is ever left out of the offline copy.
function stampServiceWorker() {
  const files = ['./', 'index.html', 'manifest.webmanifest'];
  const add = (p) => { if (!files.includes(p)) files.push(p); };
  for (const m of page.matchAll(/<script src="([^":]+)"><\/script>/g)) add(m[1]);
  for (const m of page.matchAll(/url\((lib\/fonts\/[^)]+\.woff2)\)/g)) add(m[1]);
  for (const m of page.matchAll(/href="(icons\/[^"]+)"/g)) add(m[1]);
  for (const i of JSON.parse(read('manifest.webmanifest').toString('utf8')).icons || []) add(i.src.replace(/^\.\//, ''));
  for (const f of files) if (f !== './') read(f);   // (throws if a file is missing)
  const stamp = `var CACHE = 'little-creature-${ver.code}-${ver.built.replace(/[^0-9]/g, '').slice(0, 14)}';\n` +
    `var FILES = [\n  ${files.map((f) => `'${f}'`).join(', ').replace(/(.{100,}?), /g, '$1,\n  ')}\n];\n`;
  const sw = read('sw.js').toString('utf8');
  const re = /var CACHE = [^\n]*\nvar FILES = \[[\s\S]*?\];\n/;
  if (!re.test(sw)) throw new Error('could not find the stamp in sw.js');
  writeFileSync(join(ROOT, 'sw.js'), sw.replace(re, stamp));
  console.log(`sw.js  ${files.length} files`);
}
stampServiceWorker();
bundle(page, 'dist/LittleCreature.html');
const full = page
  .replace('<script src="src/main.js"></script>', '<script src="src/cheats.js"></script>\n  <script src="src/main.js"></script>')
  .replace(/<title>[^<]*<\/title>/, '<title>Little Creature (TEST: everything unlocked)</title>');
if (!full.includes('src/cheats.js')) throw new Error('could not add the cheats to the test build');
bundle(full, 'dist/LittleCreature_full.html');
